const fs = require('fs');
const delay = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const pages = await (await fetch('http://127.0.0.1:9223/json')).json();
  const ws = new WebSocket(pages.find(p => p.type === 'page').webSocketDebuggerUrl);
  await new Promise(r => ws.addEventListener('open', r, {once:true}));
  let sequence = 0; const pending = new Map();
  ws.addEventListener('message', e => {const m=JSON.parse(e.data); if(pending.has(m.id)){const {resolve,reject}=pending.get(m.id);pending.delete(m.id);m.error?reject(m.error):resolve(m.result);}});
  const send = (method,params={}) => new Promise((resolve,reject)=>{const id=++sequence;pending.set(id,{resolve,reject});ws.send(JSON.stringify({id,method,params}));});
  const evaluate = async expression => {const r=await send('Runtime.evaluate',{expression,returnByValue:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result.value;};
  const until = async expression => {for(let i=0;i<100;i++){if(await evaluate(expression))return;await delay(300);}throw Error('Timed out: '+expression);};
  const screenshot = async name => {const r=await send('Page.captureScreenshot',{format:'png'});fs.writeFileSync('artifacts/'+name,Buffer.from(r.data,'base64'));};
  await send('Emulation.setDeviceMetricsOverride',{width:1280,height:1000,deviceScaleFactor:1,mobile:false});
  await send('Page.navigate',{url:'http://127.0.0.1:8000/events'});
  await until("document.querySelectorAll('.event-link').length > 0");
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:5,y:5});
  await delay(300);
  const resting=await evaluate("[...document.querySelectorAll('.event-preview')].every(e=>getComputedStyle(e).visibility==='hidden' && e.getBoundingClientRect().height===0)");
  if(!resting)throw Error('Previews visible at rest');
  if(!await evaluate("[...document.querySelectorAll('.event-preview img')].every(i=>!i.hasAttribute('src'))"))throw Error('Image requested before hover');
  await screenshot('events-names-only.png');
  const pos=await evaluate("(()=>{const r=document.querySelector('.event-link .event-name').getBoundingClientRect();return {x:r.x+30,y:r.y+20}})()");
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',...pos});
  await until("getComputedStyle(document.querySelector('.event-preview')).visibility==='visible' && document.querySelector('.event-preview').getBoundingClientRect().height>100");
  await until("[...document.querySelectorAll('.event-link:first-child img')].every(i=>i.complete&&i.naturalWidth>0)");
  await delay(350); await screenshot('events-hover.png');
  await send('Input.dispatchMouseEvent',{type:'mouseMoved',x:5,y:5});
  await evaluate("document.querySelector('.event-link').focus()");
  await delay(350);
  await delay(200);
  if(!await evaluate("document.querySelector('.event-preview').hidden && !document.querySelector('.event-preview img')"))throw Error('Preview visible after pointer left');
  await evaluate("document.querySelector('.event-link').click()");
  await delay(70);
  if(!await evaluate("app.classList.contains('page-leaving') && Number(getComputedStyle(app).opacity)<1"))throw Error('Page fade-out missing');
  await until("document.querySelectorAll('.fight-row').length>0");
  await until("[...document.querySelectorAll('.fight-row:first-child img')].every(i=>i.complete&&i.naturalWidth>0)");
  if(await evaluate("getComputedStyle(document.querySelector('.fight-row .fight-matchup')).backgroundImage!=='none'"))throw Error('Gradient remains');
  await screenshot('event-card-flat.png');
  await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await delay(400);await screenshot('event-card-mobile.png');
  if(await evaluate('document.documentElement.scrollWidth>window.innerWidth'))throw Error('Mobile horizontal overflow');
  await send('Page.navigate',{url:'http://127.0.0.1:8000/events'});
  await until("document.querySelectorAll('.event-link').length>0");
  await screenshot('events-mobile.png');
  await send('Page.navigate',{url:'http://127.0.0.1:8000/'});
  await until("document.querySelectorAll('.event-link').length>0 && app.classList.contains('page-ready')");
  if(await evaluate("document.querySelectorAll('#app img, #app svg').length"))throw Error('Home portraits visible before hover');
  console.log('PASS: home has no portraits before hover, page fade,  names only, hover images, fade-out after leaving, full-card navigation, no gradients, mobile overflow.');
  await send('Browser.close');
  ws.close();
})().catch(e=>{console.error(e);process.exit(1)});
